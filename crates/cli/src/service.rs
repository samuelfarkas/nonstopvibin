//! The systemd user service: its unit text, installing, updating and removing it, and finding
//! the data directory of the service that runs.

use std::ffi::OsStr;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};
use std::time::{Duration, SystemTime};

use nsv_agents::agent_environment;
use nsv_domain::time::epoch_ms;
use nsv_files::{DataDir, write_atomic};
use nsv_server::Session;

use crate::{CliError, SERVER_PORT, complain, say, user};

pub(crate) const UNIT: &str = "nonstopvibin.service";

/// systemd quoting: C-style escapes inside double quotes; `%` starts a specifier, and `$` a
/// variable in `ExecStart` arguments (not the executable).
pub(crate) fn unit_quote(value: &str, dollar: bool) -> Result<String, CliError> {
    if value.chars().any(|c| c < ' ' || c == '\u{7f}') {
        return Err(CliError::new(format!(
            "Cannot write a control character to the service unit: {}",
            serde_json::Value::String(value.to_owned())
        )));
    }
    let mut quoted = value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('%', "%%");
    if dollar {
        quoted = quoted.replace('$', "$$");
    }
    Ok(format!("\"{quoted}\""))
}

/// The unit `service install` writes.
pub(crate) fn render_unit(
    executable: &str,
    args: &[String],
    environment: &[(String, String)],
) -> Result<String, CliError> {
    let mut exec = vec![unit_quote(executable, false)?];
    for arg in args {
        exec.push(unit_quote(arg, true)?);
    }
    let mut lines = String::new();
    for (key, value) in environment {
        let quoted = unit_quote(&format!("{key}={value}"), false)?;
        let _infallible = writeln!(lines, "Environment={quoted}");
    }
    Ok(format!(
        "# Generated by `nonstopvibin service install`. Re-run it to change options.
[Unit]
Description=NonstopVibin AI subscription gateway
StartLimitIntervalSec=120
StartLimitBurst=5

[Service]
Type=simple
ExecStart={}
{lines}Restart=on-failure
RestartSec=2
KillMode=mixed
TimeoutStopSec=30
UMask=0077
NoNewPrivileges=true
# Deliberately not set: PrivateTmp (the agent credential socket lives in
# /tmp/nonstopvibin-UID-*), ProtectHome/ProtectSystem (agent settings are
# written to ~/.claude, ~/.codex and similar), MemoryDenyWriteExecute (the
# JavaScript JIT needs it).

[Install]
WantedBy=default.target
",
        exec.join(" ")
    ))
}

/// Removes every ` "<flag>" "<value>"` whose value is non-empty and made of `allowed` bytes.
fn remove_flag(command: &str, flag: &str, allowed: fn(u8) -> bool) -> String {
    let prefix = format!(" \"{flag}\" \"");
    let mut kept = String::with_capacity(command.len());
    let mut rest = command;
    while let Some(start) = rest.find(&prefix) {
        let after = rest.get(start + prefix.len()..).unwrap_or("");
        let value = after.bytes().take_while(|b| allowed(*b)).count();
        let closed = value > 0 && after.as_bytes().get(value) == Some(&b'"');
        let end = if closed {
            start + prefix.len() + value + 1
        } else {
            start + prefix.len()
        };
        if closed {
            kept.push_str(rest.get(..start).unwrap_or(""));
        } else {
            kept.push_str(rest.get(..end).unwrap_or(""));
        }
        rest = rest.get(end..).unwrap_or("");
    }
    kept.push_str(rest);
    kept
}

/// Changes only what was given in an existing unit: its port, its allowed hosts and the
/// environment the installing shell sets. Custom paths, arguments and agent directories stay.
pub(crate) fn update_unit(
    previous: &str,
    port: Option<u16>,
    allow_hosts: Option<&[String]>,
    environment: &[(String, String)],
) -> Result<String, CliError> {
    let mut unit = previous.to_owned();
    if port.is_some() || allow_hosts.is_some() {
        let exec = unit
            .split('\n')
            .find_map(|line| {
                line.strip_prefix("ExecStart=")
                    .filter(|rest| !rest.is_empty())
            })
            .filter(|command| command.contains("\"serve\""))
            .ok_or_else(|| {
                CliError::new(
                    "Cannot update this custom ExecStart. Edit the service unit directly instead.",
                )
            })?
            .to_owned();
        let mut command = exec.clone();
        if let Some(port) = port {
            command = remove_flag(&command, "--port", |b| b.is_ascii_digit());
            let _infallible = write!(command, " \"--port\" \"{port}\"");
        }
        if let Some(hosts) = allow_hosts {
            command = remove_flag(&command, "--allow-host", |b| {
                b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'.' || b == b'-'
            });
            for host in hosts {
                let quoted = unit_quote(host, true)?;
                let _infallible = write!(command, " \"--allow-host\" {quoted}");
            }
        }
        unit = unit.replacen(
            &format!("ExecStart={exec}"),
            &format!("ExecStart={command}"),
            1,
        );
    }
    for (key, value) in environment {
        let line = format!(
            "Environment={}",
            unit_quote(&format!("{key}={value}"), false)?
        );
        let prefix = format!("Environment=\"{key}=");
        let existing = unit
            .split('\n')
            .find(|candidate| candidate.starts_with(&prefix) && candidate.ends_with('"'))
            .map(str::to_owned);
        unit = match existing {
            Some(existing) => unit.replacen(&existing, &line, 1),
            None => unit.replacen("[Service]\n", &format!("[Service]\n{line}\n"), 1),
        };
    }
    Ok(unit)
}

fn unit_path() -> Result<PathBuf, CliError> {
    let config = std::env::var_os("XDG_CONFIG_HOME")
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
        .or_else(|| std::env::home_dir().map(|home| home.join(".config")))
        .ok_or_else(|| CliError::new("There is no home directory."))?;
    Ok(config.join("systemd/user").join(UNIT))
}

fn read_optional(path: &Path) -> Result<Option<String>, CliError> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(CliError::new(error.to_string())),
    }
}

/// `systemctl --user <args>`; `None` when it cannot run at all.
pub(crate) fn systemctl(args: &[&str]) -> Option<Output> {
    Command::new("systemctl")
        .arg("--user")
        .args(args)
        .stdin(Stdio::null())
        .output()
        .ok()
}

fn stderr_of(output: Option<&Output>) -> String {
    output.map_or_else(String::new, |output| {
        String::from_utf8_lossy(&output.stderr).trim().to_owned()
    })
}

fn require_user_manager() -> Result<(), CliError> {
    if !cfg!(target_os = "linux") {
        return Err(CliError::new(
            "The service commands need Linux with systemd.",
        ));
    }
    let runtime = std::env::var_os("XDG_RUNTIME_DIR").filter(|value| !value.is_empty());
    let reachable = runtime.is_some()
        && systemctl(&["show-environment"]).is_some_and(|output| output.status.success());
    if reachable {
        return Ok(());
    }
    let reason = if runtime.is_some() {
        "."
    } else {
        " (XDG_RUNTIME_DIR is not set)."
    };
    Err(CliError::new(format!(
        "The systemd user manager is not reachable{reason}
Log in over SSH directly as this user (not through su or sudo).
Check your distribution's systemd user session and D-Bus packages, then reconnect (see docs/server.md).
Without systemd, install with --no-service and run `nonstopvibin serve` in a terminal or under your own supervisor."
    )))
}

/// The data directory `url` and `status` look in: the shell's override, or else the one the
/// running user service was started with, read from its live environment.
pub(crate) fn discovery_directory() -> Result<DataDir, CliError> {
    if let Some(chosen) = DataDir::from_environment().map_err(CliError::from_display)? {
        return Ok(chosen);
    }
    if !cfg!(target_os = "linux") {
        return home();
    }
    let pid = systemctl(&["show", UNIT, "--property=MainPID", "--value"])
        .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_owned())
        .filter(|pid| !pid.is_empty() && pid != "0" && pid.bytes().all(|b| b.is_ascii_digit()));
    if let Some(pid) = pid {
        match std::fs::read(format!("/proc/{pid}/environ")) {
            Ok(environment) => {
                let prefix = format!("{}=", DataDir::VARIABLE);
                let found = environment
                    .split(|byte| *byte == 0)
                    .find_map(|entry| entry.strip_prefix(prefix.as_bytes()))
                    .map(|value| String::from_utf8_lossy(value).into_owned());
                if let Some(chosen) = found
                    .map(|value| DataDir::chosen(OsStr::new(&value)))
                    .transpose()
                    .map_err(CliError::from_display)?
                    .flatten()
                {
                    return Ok(chosen);
                }
            }
            Err(error)
                if matches!(
                    error.kind(),
                    std::io::ErrorKind::NotFound | std::io::ErrorKind::PermissionDenied
                ) => {}
            Err(error) => return Err(CliError::new(error.to_string())),
        }
    }
    home()
}

/// The data directory this process serves: the environment's choice, or `~/.nonstopvibin`.
pub(crate) fn data_directory() -> Result<DataDir, CliError> {
    match DataDir::from_environment().map_err(CliError::from_display)? {
        Some(chosen) => Ok(chosen),
        None => home(),
    }
}

fn home() -> Result<DataDir, CliError> {
    DataDir::home().map_err(CliError::from_display)
}

/// Polls for half a minute until a daemon started at or after `since` answers.
async fn wait_until_running(directory: &DataDir, since: i64) -> Result<bool, CliError> {
    for _ in 0..60 {
        if let Some(session) = Session::read(directory).map_err(CliError::from_display)?
            && session.started_at >= since
            && session.probe().await.is_some()
        {
            return Ok(true);
        }
        tokio::time::sleep(Duration::from_millis(500)).await;
    }
    Ok(false)
}

fn ensure_linger() {
    let user = user();
    let linger = Command::new("loginctl")
        .args(["show-user", &user, "--property=Linger", "--value"])
        .stdin(Stdio::null())
        .output()
        .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_owned());
    if linger.is_ok_and(|value| value == "yes") {
        return;
    }
    let enabled = Command::new("loginctl")
        .args(["enable-linger", "--no-ask-password"])
        .stdin(Stdio::null())
        .output()
        .is_ok_and(|output| output.status.success());
    if enabled {
        say("Enabled lingering so the service keeps running after logout.");
        return;
    }
    complain(&format!(
        "
WARNING: could not enable lingering for this user. Without it, the service
stops when you log out and does not start at boot. Ask an administrator to run:
  sudo loginctl enable-linger {user}"
    ));
}

/// `service install [--port] [--allow-host]`.
pub(crate) async fn install(
    packaged: bool,
    port: Option<u16>,
    allow_hosts: Option<&[String]>,
) -> Result<(), CliError> {
    require_user_manager()?;
    if !packaged {
        return Err(CliError::new(
            "Install the service from the packaged release, not from source.",
        ));
    }
    let chosen = DataDir::from_environment().map_err(CliError::from_display)?;
    let path = unit_path()?;
    let previous = read_optional(&path)?;
    let mut args = vec![
        "serve".to_owned(),
        "--port".to_owned(),
        port.unwrap_or(SERVER_PORT).to_string(),
    ];
    for host in allow_hosts.unwrap_or_default() {
        args.extend(["--allow-host".to_owned(), host.clone()]);
    }
    // The unit carries the shell's data directory, resolved, and the agent variables as set.
    let environment: Vec<(String, String)> = chosen
        .map(|directory| {
            (
                DataDir::VARIABLE.to_owned(),
                directory.path().display().to_string(),
            )
        })
        .into_iter()
        .chain(agent_environment().into_iter().filter_map(|key| {
            let value = std::env::var(key).ok().filter(|value| !value.is_empty())?;
            Some((key.to_owned(), value))
        }))
        .collect();
    let unit = if let Some(previous) = &previous {
        update_unit(previous, port, allow_hosts, &environment)?
    } else {
        let executable = std::env::current_exe()
            .and_then(std::fs::canonicalize)
            .map_err(|error| CliError::new(error.to_string()))?;
        render_unit(&executable.to_string_lossy(), &args, &environment)?
    };
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|error| CliError::new(error.to_string()))?;
    }
    write_atomic(&path, unit.as_bytes(), 0o600)
        .map_err(|error| CliError::new(error.to_string()))?;
    let previous_port = previous.as_deref().and_then(|unit| {
        unit.split("\"--port\" \"").skip(1).find_map(|after| {
            let digits: String = after.chars().take_while(char::is_ascii_digit).collect();
            (!digits.is_empty() && after.get(digits.len()..)?.starts_with('"')).then_some(digits)
        })
    });
    if let (Some(port), Some(previous_port)) = (port, previous_port)
        && previous_port != port.to_string()
    {
        complain(&format!(
            "The port changed from {previous_port} to {port}. Startup moves connected agents to the new port; restart running agents (or /reload in pi). Any connection it cannot update is reported in the app; resolve it in Connect agents."
        ));
    }
    let since = epoch_ms(SystemTime::now()) - 1000;
    for args in [
        &["daemon-reload"][..],
        &["enable", UNIT][..],
        &["restart", UNIT][..],
    ] {
        let result = systemctl(args);
        if !result
            .as_ref()
            .is_some_and(|output| output.status.success())
        {
            return Err(CliError::new(format!(
                "systemctl --user {} failed:\n{}",
                args.join(" "),
                stderr_of(result.as_ref())
            )));
        }
    }
    say(&format!("Installed {}", path.display()));
    if !wait_until_running(&discovery_directory()?, since).await? {
        return Err(CliError::new(
            "The service did not become ready. Check `journalctl --user -u nonstopvibin -e`.",
        ));
    }
    say("NonstopVibin is running as a user service. Run `nonstopvibin status` for its port.");
    ensure_linger();
    say("Run `nonstopvibin url` for the session link.");
    Ok(())
}

/// `service unit <executable>`: the installed unit's path, refusing a unit that runs another
/// executable. `install.sh` asks before an upgrade.
pub(crate) fn unit(executable: &str) -> Result<Option<PathBuf>, CliError> {
    let path = unit_path()?;
    let Some(unit) = read_optional(&path)? else {
        return Ok(None);
    };
    if !unit.contains(&unit_quote(executable, false)?) {
        return Err(CliError::new(format!(
            "The existing service uses another executable. Upgrade at its original --prefix, or edit {} first. Nothing was changed.",
            path.display()
        )));
    }
    Ok(Some(path))
}

/// `service uninstall`: stops and removes the unit; the data stays.
pub(crate) fn uninstall() -> Result<(), CliError> {
    require_user_manager()?;
    let directory = discovery_directory()?;
    let path = unit_path()?;
    if path.exists() {
        let disable = systemctl(&["disable", "--now", UNIT]);
        if !disable
            .as_ref()
            .is_some_and(|output| output.status.success())
        {
            return Err(CliError::new(format!(
                "Could not stop and disable the service:\n{}",
                stderr_of(disable.as_ref())
            )));
        }
    }
    match std::fs::remove_file(&path) {
        Err(error) if error.kind() != std::io::ErrorKind::NotFound => {
            return Err(CliError::new(error.to_string()));
        }
        _ => {}
    }
    let reload = systemctl(&["daemon-reload"]);
    if !reload
        .as_ref()
        .is_some_and(|output| output.status.success())
    {
        return Err(CliError::new(format!(
            "Could not reload the user manager:\n{}",
            stderr_of(reload.as_ref())
        )));
    }
    say(&format!(
        "Removed {}.\nYour data remains in {}. Lingering is unchanged; run `loginctl disable-linger` if you no longer need it.",
        path.display(),
        directory.path().display()
    ));
    Ok(())
}
