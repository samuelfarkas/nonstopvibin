//! `OpenCode`: one plugin per profile in its plugins directory. The plugin asks the credential
//! socket itself, so there is no helper. The app no longer offers `OpenCode`; existing
//! connections are still restored and can be disconnected.

use std::path::Path;

use nsv_domain::wire::Profile;

use crate::connection::{
    CATALOG_QUERY, ConfigDirectory, Definition, native_provider, owned_file, profile_endpoint,
    same_text,
};
use crate::credential::credential_client;
use crate::json;

pub(crate) const DEFINITION: Definition = Definition {
    version: 3,
    older_needs_reconnect: false,
    directory: Some(ConfigDirectory {
        variable: "OPENCODE_CONFIG_DIR",
        xdg: Some("opencode"),
        home: &[".config", "opencode"],
    }),
    project_root: None,
    file: |profile, _| {
        vec![
            "plugins".to_owned(),
            format!("nonstopvibin-{}.js", profile.id),
        ]
    },
    helper: false,
    configure: |context| plugin(context.profile, context.socket, context.port),
    merge: owned_file,
    unchanged: same_text,
    retain: None,
    launch_settings: None,
    command: |_, _| "opencode".to_owned(),
    instructions: |profile| {
        format!(
            "Use /models to choose nonstopvibin · {}. Needs OpenCode 1.18.29 or later; background model overrides to another provider are rejected.",
            profile.name
        )
    },
};

fn plugin(profile: &Profile, socket: &Path, port: u16) -> String {
    let failure = format!(
        "new Error(\"Open nonstopvibin and start {}. If its port changed, reconnect OpenCode in the app.\")",
        profile.slug
    );
    format!(
        r#"// Generated by nonstopvibin. Credentials are requested for discovery and inference.
import http from "node:http";
const providerID = {provider};
const baseURL = {base};
{credential}
export default async function () {{
  return {{
    async config(config) {{
      config.provider ??= {{}};
      if (Object.hasOwn(config.provider, providerID)) throw new Error("Remove the conflicting nonstopvibin provider from OpenCode config, then restart OpenCode.");
      const key = await credential();
      const response = await fetch(baseURL + {models}, {{
        headers: {{ Authorization: "Bearer " + key }}, redirect: "error", signal: AbortSignal.timeout(30000)
      }});
      if (!response.ok) throw new Error("Could not refresh nonstopvibin models. Open Connect agents and check this profile's catalog.");
      const {{ models }} = await response.json();
      if (!Array.isArray(models) || !models.length) throw new Error("The nonstopvibin catalog is empty.");
      config.provider[providerID] = {{
        npm: "@ai-sdk/openai-compatible",
        name: {name},
        models: Object.fromEntries(models.map(({{ id, ...model }}) => [id, model])),
        options: {{
          baseURL,
          async fetch(input, init) {{
            const url = new URL(input instanceof Request ? input.url : input);
            if (url.href !== baseURL + "/chat/completions") throw new Error("nonstopvibin refused a request outside this profile's endpoint.");
            const key = await credential();
            const headers = new Headers(init?.headers ?? (input instanceof Request ? input.headers : undefined));
            headers.set("Authorization", "Bearer " + key);
            const response = await fetch(input, {{ ...init, headers, redirect: "error" }});
            if (response.status >= 300 && response.status < 400) throw new Error("nonstopvibin refused a redirect.");
            return response;
          }},
        }},
      }};
    }},
    "experimental.provider.small_model": async ({{ provider }}, output) => {{
      if (provider.id === providerID) output.model = Object.values(provider.models)[0];
    }},
    "chat.params": async ({{ message, model }}) => {{
      if (message.model.providerID === providerID && model.providerID !== providerID) throw new Error("OpenCode's background model points outside this nonstopvibin profile. Remove its small_model or agent model override, then restart OpenCode.");
    }},
  }};
}}
"#,
        provider = json::string(&native_provider(profile)),
        base = json::string(&profile_endpoint(port, profile.slug.as_str())),
        credential = credential_client(profile, socket, port, &failure),
        models = json::string(&format!("/models?{CATALOG_QUERY}=opencode")),
        name = json::string(&format!("nonstopvibin · {}", profile.name)),
    )
}
