//! pi: one extension per profile in its extensions directory. It registers the profile's models
//! and shares the `/nv` profile controls with the other extensions.

use std::path::Path;

use nsv_domain::wire::Profile;

use crate::connection::{
    CATALOG_QUERY, ConfigDirectory, Definition, native_provider, owned_file, profile_base,
    profile_endpoint, same_text, shell_quote, text,
};
use crate::credential::client_key_source;
use crate::json;
use crate::pi_controls::PI_PROFILE_CONTROLS;

/// Characters a pi notice or label must not show, as a JavaScript regular expression literal:
/// controls, format characters and separators.
const UNPRINTABLE: &str = r"/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/gu";

const DIRECTORY: ConfigDirectory = ConfigDirectory {
    variable: "PI_CODING_AGENT_DIR",
    xdg: None,
    home: &[".pi", "agent"],
};

pub(crate) const DEFINITION: Definition = Definition {
    version: 7,
    older_needs_reconnect: true,
    directory: Some(DIRECTORY),
    project_root: None,
    // Versions before 6 named the file by profile ID; reconnecting renames it.
    file: |profile, version| {
        let name = if version < 6 {
            profile.id.as_str()
        } else {
            profile.slug.as_str()
        };
        vec!["extensions".to_owned(), format!("nonstopvibin-{name}.js")]
    },
    helper: true,
    configure: |context| {
        extension(
            context.profile,
            context.helper,
            context.port,
            context.pi_preferences,
        )
    },
    merge: owned_file,
    unchanged: same_text,
    retain: None,
    launch_settings: None,
    command: |_, _| "pi".to_owned(),
    instructions: |profile| {
        format!(
            "Choose {} once with /nv; pi remembers the profile and model for this repository, including /new. Use native /model to switch models. The footer shows the active profile. App startup updates connected extensions automatically; restart pi or /reload to load changes. Skip /login: a stored key would override the credential helper. Needs pi 0.85.1 or later.",
            profile.name
        )
    },
};

/// The extension states its own imports; the controls state theirs.
fn extension(profile: &Profile, helper: &Path, port: u16, preferences: &Path) -> String {
    let provider = native_provider(profile);
    let endpoint = profile_endpoint(port, profile.slug.as_str());
    let printable = |text: &str| format!("{}.replace({UNPRINTABLE}, \" \")", json::string(text));
    let home: Vec<String> = DIRECTORY
        .home
        .iter()
        .map(|name| json::string(name))
        .collect();
    let controls_profile = format!(
        "{{\"provider\":{},\"name\":{},\"slug\":{}}}",
        json::string(&provider),
        json::string(&profile.name),
        json::string(profile.slug.as_str())
    );
    format!(
        r#"// Generated by nonstopvibin. Refresh the complete profile catalog at startup or /reload.
import {{ execFile }} from "node:child_process";
import {{ promisify }} from "node:util";
import {{ homedir }} from "node:os";
import {{ readFile as readModelsStore }} from "node:fs/promises";
import {{ join as joinPath }} from "node:path";
import {{ getBuiltinModel }} from "@earendil-works/pi-ai/providers/all";
// pi's own catalog knows these vendors' names, thinking levels, and quirks.
const builtin = {{ "anthropic-messages": "anthropic", "openai-responses": "openai" }};
// pi refreshes vendor catalogs into models-store.json; the bundled catalog lags behind new models
// (e.g. claude-opus-5-5 rejects thinking.type=disabled, which only the refreshed entry declares).
async function refreshedModel(vendor, id) {{
  try {{
    const store = JSON.parse(await readModelsStore(joinPath(process.env.{variable} || joinPath(homedir(), {home}), "models-store.json"), "utf8"));
    return store[vendor]?.models?.find((model) => model.id === id);
  }} catch {{
    return undefined;
  }}
}}
{PI_PROFILE_CONTROLS}
export default async function (pi) {{
  let models = [];
  try {{
    const {{ stdout }} = await promisify(execFile)({helper}, [], {{ timeout: 10000, maxBuffer: 128 }});
    const key = stdout.trim();
    if (!/^{key}$/.test(key)) throw new Error("Invalid nonstopvibin credential.");
    const response = await fetch({models}, {{
      headers: {{ Authorization: "Bearer " + key }}, redirect: "error", signal: AbortSignal.timeout(30000)
    }});
    if (!response.ok) throw new Error("Could not refresh nonstopvibin models. Open Connect agents and check this profile's catalog.");
    ({{ models }} = await response.json());
    if (!Array.isArray(models) || !models.length) throw new Error("The nonstopvibin catalog is empty.");
    models = await Promise.all(models.map(async (model) => {{
      const {{ provider, headers, compat, ...known }} = getBuiltinModel(builtin[model.api], model.id) ?? await refreshedModel(builtin[model.api], model.id) ?? {{}};
      // Keep pi's effort fallback; native tool changes use the builtin model's capabilities.
      // pi sends its session id only when asked; without one the core fingerprints the whole conversation on every request.
      return {{ ...model, ...known, compat: {{ ...compat, supportsMidConvoEffort: false, sendSessionAffinityHeaders: true }}, api: model.api, baseUrl: model.api === "anthropic-messages" ? {base} : {endpoint} }};
    }}));
    pi.registerProvider({provider}, {{
      name: {name}, baseUrl: {endpoint}, apiKey: {api_key},
      models,
    }});
  }} catch {{
    pi.on("session_start", (_event, ctx) => {{
      // During extension loading unregisterProvider only cancels pending registrations.
      pi.unregisterProvider({provider});
      ctx.ui.notify({notice}, "warning");
    }});
  }}
  connectProfileControls(pi, {controls_profile}, {preferences});
}}
"#,
        variable = DIRECTORY.variable,
        home = home.join(", "),
        helper = json::string(&text(helper)),
        key = client_key_source(),
        models = json::string(&format!("{endpoint}/models?{CATALOG_QUERY}=pi")),
        base = json::string(&profile_base(port, profile.slug.as_str())),
        endpoint = json::string(&endpoint),
        provider = json::string(&provider),
        name = printable(&profile.name),
        api_key = json::string(&format!("!{}", shell_quote(&text(helper)))),
        notice = printable(&format!(
            "Could not load {}'s nonstopvibin models. The profile may be stopped, deleted, or have no available models. Check Connect agents and reconnect, then /reload. Use /nv to choose another profile.",
            profile.name
        )),
        preferences = json::string(&text(preferences)),
    )
}
