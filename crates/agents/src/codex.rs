//! Codex: one `<provider>.config.toml` profile file in `CODEX_HOME`, selected with
//! `codex --profile`. Codex writes its own runtime state and model choice into it, so merging is
//! line-based, as the TypeScript server did it, not a TOML round trip.

use std::path::Path;

use nsv_domain::endpoint::{CATALOG_HEADER, profile_endpoint};
use nsv_domain::js;
use nsv_domain::wire::Profile;

use crate::connection::{ConfigDirectory, Definition, native_provider, same_text, text};
use crate::error::{AgentError, conflict};

pub(crate) const DEFINITION: Definition = Definition {
    version: 3,
    older_needs_reconnect: false,
    directory: Some(ConfigDirectory {
        variable: "CODEX_HOME",
        xdg: None,
        home: &[".codex"],
    }),
    project_root: None,
    // `codex --profile <name>` reads `<name>.config.toml`.
    file: |profile, _| vec![format!("{}.config.toml", native_provider(profile))],
    helper: true,
    configure: |context| {
        configuration(
            context.profile,
            context.input.other_providers,
            context.helper,
            context.port,
        )
    },
    merge,
    unchanged: same_text,
    retain: None,
    launch_settings: None,
    command: |profile, _| format!("codex --profile {}", native_provider(profile)),
    instructions: |_| {
        "Works in any project. Pick a model with /model before the first prompt; Codex's built-in default may not exist here. Needs Codex 0.140.0 or later.".to_owned()
    },
};

pub(crate) fn configuration(
    profile: &Profile,
    other_providers: Option<bool>,
    helper: &Path,
    port: u16,
) -> String {
    let provider = native_provider(profile);
    // Only without other providers: the gateway then filters the catalog to Codex's vendor.
    let tag = if other_providers == Some(false) {
        format!(
            "\nhttp_headers = {{ {} = \"codex\" }}",
            js::quote(CATALOG_HEADER)
        )
    } else {
        String::new()
    };
    format!(
        r#"# Generated by nonstopvibin. Select with codex --profile {provider}.
model_provider = {quoted}

[model_providers.{provider}]
name = {name}
base_url = {base}
wire_api = "responses"{tag}

[model_providers.{provider}.auth]
command = {helper}
timeout_ms = 5000
refresh_interval_ms = 300000
"#,
        quoted = js::quote(&provider),
        name = js::quote(&format!("nonstopvibin · {}", profile.name)),
        base = js::quote(&profile_endpoint(port, profile.slug.as_str())),
        helper = js::quote(&text(helper)),
    )
}

/// A configuration split into our connection lines, the user's native model preferences and
/// the runtime state Codex records.
struct Split<'a> {
    connection: Option<String>,
    preferences: Vec<&'a str>,
    state: Vec<&'a str>,
}

fn split(content: Option<&str>) -> Split<'_> {
    let mut preferences = Vec::new();
    let mut state = Vec::new();
    let connection = content.map(|content| {
        let mut table = false;
        let mut runtime_state = false;
        let kept: Vec<&str> = content
            .split('\n')
            .filter(|&line| {
                if line.trim_start_matches(js::is_space).starts_with('[') {
                    table = true;
                    // Codex records hook approvals and model-picker notices here.
                    runtime_state = runtime_state_header(line);
                }
                if runtime_state {
                    state.push(line);
                    return false;
                }
                // Native /model owns scalar preferences, not provider or auth routing.
                if !table && preference(line) {
                    preferences.push(line);
                    return false;
                }
                true
            })
            .collect();
        js::trim(&kept.join("\n")).to_owned()
    });
    Split {
        connection,
        preferences,
        state,
    }
}

fn merge(
    current: Option<&str>,
    previous: Option<&str>,
    next: Option<&str>,
) -> Result<Option<String>, AgentError> {
    let saved = split(current);
    let old = split(previous);
    if current.is_some()
        && saved.connection != old.connection
        && saved.connection != split(next).connection
    {
        return Err(conflict());
    }
    if current.is_some() && previous == next {
        return Ok(current.map(str::to_owned));
    }
    let lines: Vec<&str> = saved
        .preferences
        .iter()
        .copied()
        .filter(|line| !old.preferences.contains(line))
        .chain(next)
        .chain(saved.state.iter().copied())
        .collect();
    let result = lines.join("\n");
    Ok((!result.is_empty()).then_some(result))
}

/// `/^\s*\[(?:hooks\.state(?:\."(?:[^"\\]|\\.)*")?|tui\.model_availability_nux)\]\s*(?:#.*)?$/`
fn runtime_state_header(line: &str) -> bool {
    let Some(rest) = line.trim_start_matches(js::is_space).strip_prefix('[') else {
        return false;
    };
    let rest = if let Some(rest) = rest.strip_prefix("hooks.state") {
        // The quoted key is optional: without a `]` after it, the header has no key.
        match rest
            .strip_prefix('.')
            .and_then(quoted)
            .filter(|rest| rest.starts_with(']'))
        {
            Some(keyed) => keyed,
            None => rest,
        }
    } else if let Some(rest) = rest.strip_prefix("tui.model_availability_nux") {
        rest
    } else {
        return false;
    };
    rest.strip_prefix(']').is_some_and(comment_or_end)
}

/// `/^\s*(?:model|review_model|model_reasoning_effort|model_reasoning_summary|model_verbosity)\s*=\s*(?:"(?:[^"\\]|\\.)*"|'[^']*')\s*(?:#.*)?$/`
fn preference(line: &str) -> bool {
    const KEYS: [&str; 5] = [
        "model",
        "review_model",
        "model_reasoning_effort",
        "model_reasoning_summary",
        "model_verbosity",
    ];
    let line = line.trim_start_matches(js::is_space);
    KEYS.iter().any(|key| {
        line.strip_prefix(key)
            .map(|rest| rest.trim_start_matches(js::is_space))
            .and_then(|rest| rest.strip_prefix('='))
            .map(|rest| rest.trim_start_matches(js::is_space))
            .and_then(|rest| quoted(rest).or_else(|| single_quoted(rest)))
            .is_some_and(comment_or_end)
    })
}

/// After `"(?:[^"\\]|\\.)*"`: the text after the closing quote. `.` matches no line terminator.
fn quoted(text: &str) -> Option<&str> {
    let body = text.strip_prefix('"')?;
    let mut chars = body.char_indices();
    while let Some((index, c)) = chars.next() {
        match c {
            '"' => return body.get(index + 1..),
            '\\' => match chars.next() {
                Some((_, escaped)) if !is_line_terminator(escaped) => {}
                _ => return None,
            },
            _ => {}
        }
    }
    None
}

/// After `'[^']*'`: the text after the closing quote.
fn single_quoted(text: &str) -> Option<&str> {
    let body = text.strip_prefix('\'')?;
    body.find('\'').and_then(|end| body.get(end + 1..))
}

/// `\s*(?:#.*)?$`.
fn comment_or_end(rest: &str) -> bool {
    let rest = rest.trim_start_matches(js::is_space);
    rest.is_empty()
        || rest
            .strip_prefix('#')
            .is_some_and(|comment| !comment.contains(is_line_terminator))
}

const fn is_line_terminator(c: char) -> bool {
    matches!(c, '\n' | '\r' | '\u{2028}' | '\u{2029}')
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn preferences_are_scalar_model_settings_before_any_table() {
        for line in [
            "model = \"gpt-5\"",
            "  review_model='o3' # mine",
            "model_reasoning_effort = \"high\"   ",
            "model_verbosity = \"a \\\" b\"",
        ] {
            assert!(preference(line), "{line}");
        }
        for line in [
            "model_provider = \"x\"",
            "model = 5",
            "model = \"x\" trailing",
            "model = \"x\" # a\r",
            "models = \"x\"",
            "model = \"unterminated",
        ] {
            assert!(!preference(line), "{line}");
        }
    }

    #[test]
    fn runtime_state_headers_are_hooks_and_model_notices() {
        for line in [
            "[hooks.state]",
            "[hooks.state.\"/a/hooks.json:stop:0:0\"]",
            " [tui.model_availability_nux] # seen",
        ] {
            assert!(runtime_state_header(line), "{line}");
        }
        for line in [
            "[hooks]",
            "[hooks.state.other]",
            "[hooks.state.\"x\"] extra",
            "[model_providers.x]",
        ] {
            assert!(!runtime_state_header(line), "{line}");
        }
    }
}
