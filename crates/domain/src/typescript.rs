//! What the TypeScript side imports from this crate, written to `src/shared/generated/domain`:
//! the wire types (through `ts-rs`), the route keys, the wire vocabularies the UI lists, and
//! sample links for the renderer to read back. `bun run wire:export` writes the directory and
//! `bun run wire:check` fails while it differs.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use serde_json::json;
use ts_rs::{Config, TS};

use crate::endpoint::{Origin, loopback_origin, session_link};
use crate::id::ProfileId;
use crate::registry::{
    Agent, OAuthProvider, Protocol, Provider, ResetResultCode, RetentionDays, Strategy,
};
use crate::secret::SessionToken;
use crate::wire::*;

const HEADER: &str =
    "// Generated by `bun run wire:export` from crates/domain. Do not edit this file manually.\n";

fn directory() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/shared/generated/domain")
}

/// Writes every file of the generated directory into `out`.
fn export(out: &Path) {
    let config = Config::new().with_large_int("number").with_out_dir(out);
    macro_rules! export {
        ($($ty:ty),+ $(,)?) => { $(<$ty as TS>::export_all(&config).unwrap();)+ };
    }
    export!(
        AppState,
        Profile,
        ProfilePatch,
        AccountPatch,
        ApiAccountInput,
        ApiAccount,
        ImportSource,
        ResetCredits,
        ResetResult,
        UsageHistory,
        CatalogModel,
        Model,
        OAuthSession,
        OAuthStatus,
        AgentSetupInput,
        AgentSetup,
        AgentSelection,
        Ok,
        ClientKeyResponse,
        UsageHub,
        ApiError,
        CreateProfileBody,
        RetentionBody,
        CoreInstallBody,
        OAuthStartBody,
        StateBody,
        CallbackBody,
        ImportBody,
        ImportSourceBody,
        CreditBody,
        Provider,
        OAuthProvider,
        Protocol,
        Agent,
        Strategy,
        ResetResultCode,
    );
    std::fs::write(out.join("RouteKey.ts"), route_keys()).unwrap();
    std::fs::write(out.join("vocabulary.ts"), vocabulary()).unwrap();
    std::fs::write(out.join("renderer-urls.json"), renderer_urls()).unwrap();
}

fn route_keys() -> String {
    let keys: Vec<String> = ROUTES
        .iter()
        .map(|(method, path, _)| format!("  | \"{method} {path}\""))
        .collect();
    format!(
        "{HEADER}\n/**\n * Every route under `/api` (`ROUTES`), as \"METHOD /path\"; `:name` segments are path\n * parameters.\n */\nexport type RouteKey =\n{};\n",
        keys.join("\n")
    )
}

/// The values of the wire vocabularies the UI offers as choices, in their order.
fn vocabulary() -> String {
    let strategies = serde_json::to_string(Strategy::ALL).unwrap();
    let retention = serde_json::to_string(RetentionDays::ALL).unwrap();
    format!(
        "{HEADER}import type {{ RetentionDays }} from \"./RetentionDays\";\nimport type {{ Strategy }} from \"./Strategy\";\n\nexport const strategies: readonly Strategy[] = {strategies};\n/** Days of usage history kept; 0 keeps everything. */\nexport const retentionDays: readonly RetentionDays[] = {retention};\n"
    )
}

/// Each link a window or a session opens the renderer with, beside what it carries.
fn renderer_urls() -> String {
    const PROFILE: &str = "6f1c1a52-6d1f-4b5e-9c55-0a4b0c7e1d2f";
    const TOKEN: &str = "sample-session-token";
    let origin = Origin::parse(&loopback_origin(4100)).unwrap();
    let profile = ProfileId::parse(PROFILE).unwrap();
    let opened = |tray: bool, profile: Option<&str>, session: Option<&str>| json!({ "tray": tray, "profile": profile, "session": session });
    let samples = json!([
        { "url": origin.main_url(None), "opened": opened(false, None, None) },
        { "url": origin.main_url(Some(&profile)), "opened": opened(false, Some(PROFILE), None) },
        { "url": origin.tray_url(), "opened": opened(true, None, None) },
        {
            "url": session_link(origin.as_str(), &SessionToken::new(TOKEN)),
            "opened": opened(false, None, Some(TOKEN)),
        },
    ]);
    serde_json::to_string_pretty(&samples).unwrap() + "\n"
}

fn files(directory: &Path) -> BTreeMap<String, String> {
    std::fs::read_dir(directory)
        .unwrap()
        .map(|entry| {
            let path = entry.unwrap().path();
            let name = path.file_name().unwrap().to_str().unwrap().to_owned();
            (name, std::fs::read_to_string(&path).unwrap())
        })
        .collect()
}

#[test]
fn generated_typescript_matches() {
    let out = std::env::temp_dir().join(format!("nsv-domain-typescript-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&out);
    export(&out);
    let (exported, committed) = (files(&out), files(&directory()));
    std::fs::remove_dir_all(&out).unwrap();
    let stale: BTreeSet<&String> = exported
        .keys()
        .chain(committed.keys())
        .filter(|name| exported.get(*name) != committed.get(*name))
        .collect();
    assert!(
        stale.is_empty(),
        "src/shared/generated/domain differs from crates/domain in {stale:?}; run bun run wire:export"
    );
}

#[test]
#[ignore = "writes into the checkout; bun run wire:export runs it"]
fn write_generated_typescript() {
    let out = directory();
    if out.exists() {
        std::fs::remove_dir_all(&out).unwrap();
    }
    export(&out);
}
