//! `window.nonstopvibin`'s methods and argument limits. The helper's bridge script lists
//! [`Method::ALL`], its parser dispatches on [`Method::named`], and [`DaemonCall`]'s wire
//! names are [`Method::name`].
//!
//! [`DaemonCall`]: crate::pipe::DaemonCall

use nsv_domain::js::utf16_len;

/// `main.ts`'s zod limits, in UTF-16 code units as JavaScript counts them.
pub const OPEN_EXTERNAL_LIMIT: usize = 20_000;
pub const COPY_LIMIT: usize = 1_000_000;

/// A method a page calls on `window.nonstopvibin`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Method {
    Bootstrap,
    OpenExternal,
    Copy,
    ShowWindow,
    ReleaseWindow,
    SetLoginItem,
    GetLoginItem,
    RevealData,
    ChooseProject,
}

impl Method {
    /// Every method, in the order the bridge script defines them.
    pub const ALL: [Self; 9] = [
        Self::Bootstrap,
        Self::OpenExternal,
        Self::Copy,
        Self::ShowWindow,
        Self::ReleaseWindow,
        Self::SetLoginItem,
        Self::GetLoginItem,
        Self::RevealData,
        Self::ChooseProject,
    ];

    /// The name a page calls it by.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Bootstrap => "bootstrap",
            Self::OpenExternal => "openExternal",
            Self::Copy => "copy",
            Self::ShowWindow => "showWindow",
            Self::ReleaseWindow => "releaseWindow",
            Self::SetLoginItem => "setLoginItem",
            Self::GetLoginItem => "getLoginItem",
            Self::RevealData => "revealData",
            Self::ChooseProject => "chooseProject",
        }
    }

    #[must_use]
    pub fn named(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|method| method.name() == name)
    }

    /// The message a call with a bad argument rejects with.
    #[must_use]
    pub fn invalid_argument(self) -> String {
        format!("Invalid argument for {}.", self.name())
    }
}

/// Whether `url` is within `openExternal`'s limit.
#[must_use]
pub fn fits_external(url: &str) -> bool {
    utf16_len(url) <= OPEN_EXTERNAL_LIMIT
}

#[cfg(test)]
mod tests {
    use std::path::{Path, PathBuf};

    use super::Method;

    fn file() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../src/shared/generated/desktop/BridgeMethod.ts")
    }

    /// The method names `src/shared/desktop-bridge.ts` types one entry for each.
    fn typescript() -> String {
        let names: Vec<String> = Method::ALL
            .iter()
            .map(|method| format!("  | \"{}\"", method.name()))
            .collect();
        format!(
            "// Generated by `bun run wire:export` from crates/desktop. Do not edit this file manually.\n\n/** A method a page calls on `window.nonstopvibin` (`Method::ALL`). */\nexport type BridgeMethod =\n{};\n",
            names.join("\n")
        )
    }

    #[test]
    fn generated_typescript_matches() {
        let committed = std::fs::read_to_string(file()).unwrap_or_default();
        assert!(
            committed == typescript(),
            "src/shared/generated/desktop differs from the bridge methods; run bun run wire:export"
        );
    }

    #[test]
    #[ignore = "writes into the checkout; bun run wire:export runs it"]
    fn write_generated_typescript() {
        let file = file();
        std::fs::create_dir_all(file.parent().unwrap()).unwrap();
        std::fs::write(file, typescript()).unwrap();
    }
}
