import type { Profile } from "../shared/types.ts";
import {
  type AgentDefinition,
  catalogRequest,
  conflict,
  nativeProvider,
  profileEndpoint,
  sameText,
} from "./agent-connection.ts";

// Codex: one `<provider>.config.toml` profile file in CODEX_HOME, selected with
// `codex --profile`. Codex writes its own runtime state and model choice into it.

export function codexConfiguration(
  profile: Profile,
  otherProviders: boolean | undefined,
  helper: string,
  port: number,
): string {
  const provider = nativeProvider(profile);
  return `# Generated by nonstopvibin. Select with codex --profile ${provider}.
model_provider = ${JSON.stringify(provider)}

[model_providers.${provider}]
name = ${JSON.stringify(`nonstopvibin · ${profile.name}`)}
base_url = ${JSON.stringify(profileEndpoint(port, profile.slug))}
wire_api = "responses"${
    otherProviders === false
      ? `\nhttp_headers = { ${JSON.stringify(catalogRequest.header)} = "codex" }`
      : ""
  }

[model_providers.${provider}.auth]
command = ${JSON.stringify(helper)}
timeout_ms = 5000
refresh_interval_ms = 300000
`;
}

function mergeCodexConfig(
  current: string | undefined,
  previous: string | undefined,
  next: string | undefined,
): string | undefined {
  const split = (content: string | undefined) => {
    const preferences: string[] = [];
    const state: string[] = [];
    let table = false;
    let runtimeState = false;
    const connection = content
      ?.split("\n")
      .filter((line) => {
        if (/^\s*\[/.test(line)) {
          table = true;
          // Codex records hook approvals and model-picker notices here.
          runtimeState =
            /^\s*\[(?:hooks\.state(?:\."(?:[^"\\]|\\.)*")?|tui\.model_availability_nux)\]\s*(?:#.*)?$/.test(
              line,
            );
        }
        if (runtimeState) {
          state.push(line);
          return false;
        }
        // Native /model owns scalar preferences, not provider/auth routing.
        if (
          !table &&
          /^\s*(?:model|review_model|model_reasoning_effort|model_reasoning_summary|model_verbosity)\s*=\s*(?:"(?:[^"\\]|\\.)*"|'[^']*')\s*(?:#.*)?$/.test(
            line,
          )
        ) {
          preferences.push(line);
          return false;
        }
        return true;
      })
      .join("\n")
      .trim();
    return { connection, preferences, state };
  };
  const saved = split(current);
  const old = split(previous);
  if (
    current !== undefined &&
    saved.connection !== old.connection &&
    saved.connection !== split(next).connection
  )
    conflict();
  if (current !== undefined && previous === next) return current;
  const preferences = saved.preferences.filter(
    (line) => !old.preferences.includes(line),
  );
  const result = [
    ...preferences,
    ...(next === undefined ? [] : [next]),
    ...saved.state,
  ].join("\n");
  return result || undefined;
}

export const codex: AgentDefinition = {
  version: 3,
  olderNeedsReconnect: false,
  directory: { variable: "CODEX_HOME", home: [".codex"] },
  // `codex --profile <name>` reads `<name>.config.toml`.
  file: (profile) => [`${nativeProvider(profile)}.config.toml`],
  helper: true,
  configure: ({ profile, input, helper, port }) =>
    codexConfiguration(profile, input.otherProviders, helper, port),
  merge: mergeCodexConfig,
  unchanged: sameText,
  command: (profile) => `codex --profile ${nativeProvider(profile)}`,
  instructions: () =>
    `Works in any project. Pick a model with /model before the first prompt; Codex's built-in default may not exist here. Needs Codex 0.140.0 or later.`,
  // Only without other providers: its TOML then tags its requests with the header.
  catalog: "header",
};
