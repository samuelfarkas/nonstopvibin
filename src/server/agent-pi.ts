// pi: one extension per profile in its extensions directory. It registers the
// profile's models and shares the /nv profile controls with the other extensions.

const directory = { variable: "PI_CODING_AGENT_DIR", home: [".pi", "agent"] };

/** The extension states its own imports; the controls below state theirs. */
export function piExtension(
  profile: Profile,
  helper: string,
  port: number,
  preferences: string,
): string {
  const provider = nativeProvider(profile);
  const endpoint = profileEndpoint(port, profile.slug);
  const printable = (text: string) =>
    `${JSON.stringify(text)}.replace(${unprintable}, " ")`;
  return `// Generated by nonstopvibin. Refresh the complete profile catalog at startup or /reload.
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { homedir } from "node:os";
import { readFile as readModelsStore } from "node:fs/promises";
import { join as joinPath } from "node:path";
import { getBuiltinModel } from "@earendil-works/pi-ai/providers/all";
// pi's own catalog knows these vendors' names, thinking levels, and quirks.
const builtin = { "anthropic-messages": "anthropic", "openai-responses": "openai" };
// pi refreshes vendor catalogs into models-store.json; the bundled catalog lags behind new models
// (e.g. claude-opus-5-5 rejects thinking.type=disabled, which only the refreshed entry declares).
async function refreshedModel(vendor, id) {
  try {
    const store = JSON.parse(await readModelsStore(joinPath(process.env.${directory.variable} || joinPath(homedir(), ${directory.home.map((name) => JSON.stringify(name)).join(", ")}), "models-store.json"), "utf8"));
    return store[vendor]?.models?.find((model) => model.id === id);
  } catch {
    return undefined;
  }
}
${piProfileControls}
export default async function (pi) {
  let models = [];
  try {
    const { stdout } = await promisify(execFile)(${JSON.stringify(helper)}, [], { timeout: 10000, maxBuffer: 128 });
    const key = stdout.trim();
    if (!${clientKeyPattern}.test(key)) throw new Error("Invalid nonstopvibin credential.");
    const response = await fetch(${JSON.stringify(`${endpoint}/models?${catalogRequest.query}=pi`)}, {
      headers: { Authorization: "Bearer " + key }, redirect: "error", signal: AbortSignal.timeout(30000)
    });
    if (!response.ok) throw new Error("Could not refresh nonstopvibin models. Open Connect agents and check this profile's catalog.");
    ({ models } = await response.json());
    if (!Array.isArray(models) || !models.length) throw new Error("The nonstopvibin catalog is empty.");
    models = await Promise.all(models.map(async (model) => {
      const { provider, headers, compat, ...known } = getBuiltinModel(builtin[model.api], model.id) ?? await refreshedModel(builtin[model.api], model.id) ?? {};
      // Keep pi's effort fallback; native tool changes use the builtin model's capabilities.
      // pi sends its session id only when asked; without one the core fingerprints the whole conversation on every request.
      return { ...model, ...known, compat: { ...compat, supportsMidConvoEffort: false, sendSessionAffinityHeaders: true }, api: model.api, baseUrl: model.api === "anthropic-messages" ? ${JSON.stringify(profileBase(port, profile.slug))} : ${JSON.stringify(endpoint)} };
    }));
    pi.registerProvider(${JSON.stringify(provider)}, {
      name: ${printable(profile.name)}, baseUrl: ${JSON.stringify(endpoint)}, apiKey: ${JSON.stringify(`!${shellQuote(helper)}`)},
      models,
    });
  } catch {
    pi.on("session_start", (_event, ctx) => {
      // During extension loading unregisterProvider only cancels pending registrations.
      pi.unregisterProvider(${JSON.stringify(provider)});
      ctx.ui.notify(${printable(`Could not load ${profile.name}'s nonstopvibin models. The profile may be stopped, deleted, or have no available models. Check Connect agents and reconnect, then /reload. Use /nv to choose another profile.`)}, "warning");
    });
  }
  connectProfileControls(pi, ${JSON.stringify({ provider, name: profile.name, slug: profile.slug })}, ${JSON.stringify(preferences)});
}
`;
}

export const pi: AgentDefinition<"pi"> = {
  version: 7,
  olderNeedsReconnect: true,
  directory,
  // Versions before 6 named the file by profile ID; reconnecting renames it.
  file: (profile, version) => [
    "extensions",
    `nonstopvibin-${version < 6 ? profile.id : profile.slug}.js`,
  ],
  helper: true,
  configure: ({ profile, helper, port, piPreferences }) =>
    piExtension(profile, helper, port, piPreferences),
  merge: ownedFile,
  unchanged: sameText,
  command: () => "pi",
  instructions: (profile) =>
    `Choose ${profile.name} once with /nv; pi remembers the profile and model for this repository, including /new. Use native /model to switch models. The footer shows the active profile. App startup updates connected extensions automatically; restart pi or /reload to load changes. Skip /login: a stored key would override the credential helper. Needs pi 0.85.1 or later.`,
  entries: (models) => models.map(piModel),
};

// pi speaks each vendor's native protocol through the gateway so thinking
// levels and tool calls are not translated twice.
const piApi = (model: CatalogModel) =>
  nativeAgent(model.owned_by) === "claude"
    ? "anthropic-messages"
    : nativeAgent(model.owned_by) === "codex"
      ? "openai-responses"
      : "openai-completions";
/** pi's model entry, with the limits and prices it needs per model. */
export function piModel(model: CatalogModel) {
  const { m, cost, name } = listedModel(model, false);
  return {
    id: model.id,
    name,
    api: piApi(model),
    reasoning: m.reasoning,
    input: m.input,
    contextWindow: m.context,
    maxTokens: m.output,
    cost: {
      input: cost.input,
      output: cost.output,
      ...(cost.cache_read !== undefined && { cacheRead: cost.cache_read }),
      ...(cost.cache_write !== undefined && { cacheWrite: cost.cache_write }),
      ...(cost.tiers && {
        tiers: cost.tiers.map((t) => ({
          inputTokensAbove: t.tier.size,
          input: t.input,
          output: t.output,
          ...(t.cache_read !== undefined && { cacheRead: t.cache_read }),
          ...(t.cache_write !== undefined && { cacheWrite: t.cache_write }),
        })),
      }),
    },
  };
}
